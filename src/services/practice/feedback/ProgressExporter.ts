import {
  MockSessionState,
  TopicMastery,
  WeaknessMapResult,
  WeaknessPracticePlan,
  FeedbackRecord,
} from '../types';
import { ProgressMetricsService } from './ProgressMetricsService';

export interface ProgressExportOptions {
  includeTranscripts?: boolean; // Default false (opt-in only for privacy)
  includeWeaknessMap?: boolean; // Default true
  includePlan?: boolean; // Default true
  includeProgress?: boolean; // Default true
  exportDate?: string;
}

export class ProgressExporter {
  public static readonly CALIBRATION_REMINDER =
    'Calibration reminder: AI scores are mathematical estimates generated by language models. They may be imperfect, miss subtle conversational nuances, or disagree with human judgment. Always treat these scores as coaching signals rather than definitive hiring verdicts, and compare them against feedback from real human interviewers and mentors whenever possible.';

  /**
   * Generates a clean Markdown export of candidate coaching progress, weakness map, and practice plan.
   * Privacy Invariant: Contains ZERO raw candidate transcripts unless explicitly opted in via includeTranscripts: true.
   */
  public static generateMarkdownReport(
    data: {
      weaknessMap?: WeaknessMapResult | null;
      weaknessPlan?: WeaknessPracticePlan | null;
      sessionHistory?: MockSessionState[];
      topicMasteries?: TopicMastery[];
      feedbackRecords?: FeedbackRecord[];
    },
    options: ProgressExportOptions = {}
  ): string {
    const includeTranscripts = Boolean(options.includeTranscripts);
    const includeWeaknessMap = options.includeWeaknessMap !== false;
    const includePlan = options.includePlan !== false;
    const includeProgress = options.includeProgress !== false;
    const dateStr = options.exportDate || new Date().toISOString().split('T')[0];

    const lines: string[] = [];

    // Title & Header
    lines.push('# AI Interview Assistant - Candidate Progress & Coaching Report');
    lines.push(`*Generated on: ${dateStr}*`);
    lines.push('');

    // Calibration Reminder
    lines.push('## ⚖️ Calibration Reminder');
    lines.push(`> ${this.CALIBRATION_REMINDER}`);
    lines.push('');

    // Weakness Map Section
    if (includeWeaknessMap && data.weaknessMap) {
      lines.push('## 🎯 Weakness Map & Recurring Gaps');
      const ranked = data.weaknessMap.rankedWeaknesses || [];

      if (ranked.length === 0) {
        lines.push('No weaknesses extracted yet. Paste employer feedback to populate the map.');
      } else {
        lines.push('| Rank | Topic | Skill Area | Severity | Score | Recurring? | Requested Fix |');
        lines.push('| :--- | :--- | :--- | :--- | :--- | :--- | :--- |');

        ranked.forEach((w, idx) => {
          const recBadge = w.isRecurring ? '**YES (Recurring)**' : 'No';
          const fix = (w.requestedFixes && w.requestedFixes.length > 0) ? w.requestedFixes.join(", ").replace(/\|/g, "\\|") : "None recorded";
          lines.push(
            `| ${idx + 1} | ${w.topic} | ${w.skill} | ${w.severity}/3 | ${w.score.toFixed(2)} | ${recBadge} | ${fix} |`
          );
        });
      }

      if (data.weaknessMap.missingContentTopics && data.weaknessMap.missingContentTopics.length > 0) {
        lines.push('');
        lines.push('### ⚠️ Topics Needing Additional Question Content');
        data.weaknessMap.missingContentTopics.forEach((t) => {
          lines.push(`- **${t}**: No matching questions found in current question bank`);
        });
      }
      lines.push('');
    }

    // 7-Day Plan Section
    if (includePlan && data.weaknessPlan) {
      lines.push('## 📅 7-Day Weakness-Targeted Practice Plan');
      lines.push(`*Daily Time Budget Cap: ${data.weaknessPlan.maxDailyMinutes || 90} minutes*`);
      lines.push('');

      (data.weaknessPlan.days || []).forEach((day) => {
        lines.push(`### Day ${day.day} Practice Drills`);
        lines.push(`*Total Scheduled Time: ${day.totalTimeMinutes} minutes*`);
        lines.push('');
        lines.push('| Drill Type | Title | Duration | Target Topic | Completed |');
        lines.push('| :--- | :--- | :--- | :--- | :--- |');

        (day.drills || []).forEach((drill) => {
          const check = drill.completed ? '✅' : '⬜';
          lines.push(`| ${drill.type} | ${drill.title} | ${drill.timeBudgetMinutes}m | ${drill.targetTopic} | ${check} |`);
        });
        lines.push('');
      });
    }

    // Progress & Performance Trends Section
    if (includeProgress) {
      const summary = ProgressMetricsService.computeProgressSummary(
        data.sessionHistory || [],
        data.topicMasteries || []
      );

      lines.push('## 📈 Performance Progress & Metric Evolution');
      lines.push('');

      if (summary.isDataThin) {
        lines.push(`> ⚠️ **Baseline Status**: ${summary.dataThinMessage}`);
        lines.push('');
      } else {
        lines.push('### Summary Averages');
        lines.push(`- **Structure Score**: ${summary.averageStructure} / 5.0`);
        lines.push(`- **Concreteness Score**: ${summary.averageConcreteness} / 5.0`);
        lines.push(`- **Delivery Score**: ${summary.averageDelivery} / 5.0`);
        lines.push(`- **Average Speaking Pace**: ${summary.averageWpm} WPM`);
        lines.push('');
      }

      lines.push('### Practice Sessions Log');
      if (summary.metrics.length === 0) {
        lines.push('No completed mock sessions recorded yet.');
      } else {
        lines.push('| Session | Round | Structure | Concreteness | Delivery | Pace | Confidence Indicator |');
        lines.push('| :--- | :--- | :--- | :--- | :--- | :--- | :--- |');

        summary.metrics.forEach((m) => {
          const confLabel =
            m.confidence === 'high'
              ? '🟢 High (LLM Verified Evidence)'
              : '🟡 Low (Heuristic Estimate)';
          lines.push(
            `| ${m.sessionId} | ${m.roundType} | ${m.structureScore}/5 | ${m.concretenessScore}/5 | ${m.deliveryScore}/5 | ${m.speakingPaceWpm} WPM | ${confLabel} |`
          );
        });
      }
      lines.push('');

      // Topic Mastery Section
      if (summary.topicMasterySummary.length > 0) {
        lines.push('### Topic Mastery Status');
        lines.push('| Topic | Mastery Level | Repetitions |');
        lines.push('| :--- | :--- | :--- |');
        summary.topicMasterySummary.forEach((tm) => {
          lines.push(`| ${tm.topicId} | ${tm.masteryPercentage}% | ${tm.repetitions} |`);
        });
        lines.push('');
      }
    }

    // Raw Transcripts (Privacy Guardrail: STRICT OPT-IN ONLY)
    if (includeTranscripts && data.sessionHistory) {
      lines.push('## 📝 Full Practice Transcripts (User Opt-In)');
      lines.push('> Note: Candidate transcripts are included because you opted in to transcript export.');
      lines.push('');

      data.sessionHistory.forEach((session, sIdx) => {
        lines.push(`### Session ${sIdx + 1} (${session.roundType})`);
        session.questionHistory.forEach((q, qIdx) => {
          lines.push(`**Question ${qIdx + 1}**: ${q.question}`);
          if (q.candidateTranscript) {
            lines.push(`**Candidate Answer**: ${q.candidateTranscript}`);
          }
          lines.push('');
        });
      });
    }

    return lines.join('\n');
  }
}
